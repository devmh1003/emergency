import { h, panel, pageHeader, alertBox, isIOS } from '../dom.js';
import { t } from '../i18n.js';

function processList(steps) {
  return h('ol', { class: 'process-list' }, steps.map(([title, ...items]) => h('li', null,
    h('p', { class: 'process-heading' }, title),
    h('ul', null, items.map((i) => h('li', null, i))))));
}

function faq(items) {
  return h('div', { class: 'accordion' }, items.map(([q, a]) => h('details', null,
    h('summary', null, q),
    h('div', { class: 'accordion-body' }, a))));
}

